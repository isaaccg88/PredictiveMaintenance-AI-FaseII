"""FastAPI: 72-hour synthetic predictive maintenance, human-in-the-loop.

All machinery, timestamps, and readings are simulated. Never claim this is
an industrially validated prognostic model or an exact failure-time estimate.
"""
from __future__ import annotations
import json
import os
import sqlite3
from contextlib import asynccontextmanager
from datetime import datetime,timezone
from pathlib import Path
from typing import Annotated
import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException, Query
from pydantic import BaseModel, ConfigDict, Field

MODEL=Path(os.getenv("MODEL_PATH","artifacts/risk72h_model.joblib"))
SNAPSHOT=Path(os.getenv("SNAPSHOT_PATH","artifacts/pilot_snapshot.json"))
META=Path(os.getenv("META_PATH","artifacts/model_metadata.json"))
DB=Path(os.getenv("DB_PATH","runtime/predictions.sqlite"))
STATE={}

def connect():
    conn=sqlite3.connect(str(DB),timeout=20)
    conn.row_factory=sqlite3.Row
    return conn

def initialize():
    for path in (MODEL,SNAPSHOT,META):
        if not path.exists():
            raise FileNotFoundError(f"Missing generated asset: {path}. Run python -m src.train")
    model=joblib.load(MODEL) # only load model files generated by trusted project code
    snapshot=json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    meta=json.loads(META.read_text(encoding="utf-8"))
    if not snapshot["synthetic"] or meta["horizon_hours"]!=72:
        raise RuntimeError("Model metadata not suitable for 72h synthetic pilot")
    machines=snapshot["machines"]
    if len(machines)!=12 or len(set(m["machine_id"] for m in machines))!=12:
        raise RuntimeError("Expected exactly 12 independent pilot machines")
    STATE.update({"model":model,"machines":{m["machine_id"]:m for m in machines},
                  "metadata":meta})
    DB.parent.mkdir(parents=True,exist_ok=True)
    with connect() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS prediction_history(
             id INTEGER PRIMARY KEY AUTOINCREMENT,
             machine_id TEXT NOT NULL,
             observed_simulated_at TEXT NOT NULL,
             requested_at_utc TEXT NOT NULL,
             probability_72h REAL NOT NULL,
             risk_level TEXT NOT NULL,
             alert INTEGER NOT NULL,
             inputs_json TEXT NOT NULL,
             source TEXT NOT NULL DEFAULT 'simulated'
        )""")
        db.commit()

@asynccontextmanager
async def lifespan(app:FastAPI):
    initialize()
    yield
    STATE.clear()

app=FastAPI(title="Predictive Maintenance AI — Fase II",
    description="Synthetic educational 72h-failure risk API; never industrially validated.",
    version="0.1.0",lifespan=lifespan)

class Overrides(BaseModel):
    model_config=ConfigDict(extra="forbid")
    temperature_c:float|None=Field(default=None,ge=-20,le=200)
    vibration_mm_s:float|None=Field(default=None,ge=0,le=80)
    pressure_bar:float|None=Field(default=None,ge=0,le=50)
    rpm:float|None=Field(default=None,ge=0,le=12000)
    torque_nm:float|None=Field(default=None,ge=0,le=2000)
    wear_index:float|None=Field(default=None,ge=0,le=1)
    load_pct:float|None=Field(default=None,ge=0,le=1)
    hours_since_service:float|None=Field(default=None,ge=0,le=100000)
    temperature_avg_24h:float|None=Field(default=None,ge=-20,le=200)
    vibration_avg_24h:float|None=Field(default=None,ge=0,le=80)
    wear_delta_72h:float|None=Field(default=None,ge=-1,le=1)

class PredictRequest(BaseModel):
    model_config=ConfigDict(extra="forbid")
    machine_id:str=Field(min_length=6,max_length=6,pattern=r"^PM-\d{3}$")
    overrides:Overrides|None=None

def compute(m,overrides=None):
    data={key:m[key] for key in STATE["metadata"]["features"]}
    if overrides:
        changed=overrides.model_dump(exclude_none=True)
        data.update(changed)
    raw=float(STATE["model"].predict_proba(pd.DataFrame([data]))[0,1])
    threshold=float(STATE["metadata"]["threshold"])
    level="ALTO" if raw>=threshold else ("MEDIO" if raw>=threshold*.5 else "BAJO")
    return {"probability_72h":round(raw,6),"risk_level":level,
            "alert":raw>=threshold,"alert_threshold":threshold,
            "horizon_hours":72,"synthetic":True,"input_features":data}

@app.get("/health")
def health():
    with connect() as db:
        db.execute("SELECT 1").fetchone()
    return {"status":"ok","model_loaded":"model" in STATE,
            "database":"ok","synthetic":True,"horizon_hours":72}

@app.get("/model/info")
def model_info():
    return {**STATE["metadata"],"pilot_count":len(STATE["machines"]),
            "disclaimer":"Synthetic prototype; never real 72h predictive validity"}

@app.get("/machines")
def machines():
    return [{"machine_id":mid,"timestamp_simulated":m["timestamp"],
             "temperature_c":m["temperature_c"],
             "vibration_mm_s":m["vibration_mm_s"],
             "wear_index":m["wear_index"],
             **{k:v for k,v in compute(m).items()
                if k in ("probability_72h","risk_level","alert")}}
            for mid,m in sorted(STATE["machines"].items())]

@app.get("/telemetry/{machine_id}")
def telemetry(machine_id:str):
    m=STATE["machines"].get(machine_id)
    if m is None:raise HTTPException(status_code=404,detail="Unknown pilot machine")
    return {"synthetic":True,"machine":m}

@app.post("/predict")
def predict(body:PredictRequest):
    mid=body.machine_id
    m=STATE["machines"].get(mid)
    if m is None:raise HTTPException(status_code=404,detail="Unknown pilot machine")
    decision=compute(m,body.overrides)
    with connect() as db:
        cursor=db.execute("""INSERT INTO prediction_history
          (machine_id,observed_simulated_at,requested_at_utc,probability_72h,
           risk_level,alert,inputs_json,source)
          VALUES (?,?,?,?,?,?,?,?)""",
          (mid,m["timestamp"],datetime.now(timezone.utc).isoformat(),
           decision["probability_72h"],decision["risk_level"],
           int(decision["alert"]),json.dumps(decision["input_features"]),
           "simulated_whatif" if body.overrides else "simulated_telemetry"))
        db.commit()
        record_id=cursor.lastrowid
    return {"record_id":record_id,"machine_id":mid,
            "timestamp_simulated":m["timestamp"],
            "action":"human_review_required_if_alert",
            "limitation":"Risk of at least one failure within next 72h; NOT exact failure time",
            **decision}

@app.get("/predictions")
def history(limit:Annotated[int,Query(ge=1,le=200)]=30):
    with connect() as db:
        rows=db.execute("""SELECT id,machine_id,observed_simulated_at,
            requested_at_utc,probability_72h,risk_level,alert,source
            FROM prediction_history ORDER BY id DESC LIMIT ?""",(limit,)).fetchall()
    return [dict(x) for x in rows]
